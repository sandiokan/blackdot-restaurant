create table public.staff (
  id uuid primary key default gen_random_uuid(),
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  name text not null,
  role text not null,
  area text not null check (area in ('Sala', 'Cucina', 'Bar', 'Amministrazione')),
  phone text not null default '',
  email text not null default '',
  status text not null default 'upcoming' check (status in ('working', 'upcoming', 'absent')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, restaurant_id)
);

create table public.shifts (
  id uuid primary key default gen_random_uuid(),
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  staff_id uuid not null,
  date date not null,
  start_time time,
  end_time time,
  area text not null check (area in ('Sala', 'Cucina', 'Bar', 'Amministrazione')),
  status text not null default 'scheduled' check (status in ('scheduled', 'rest', 'cancelled')),
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint shifts_time_by_status check (
    (status = 'rest' and start_time is null and end_time is null)
    or (status in ('scheduled', 'cancelled') and start_time is not null and end_time is not null)
  ),
  foreign key (staff_id, restaurant_id) references public.staff(id, restaurant_id) on delete cascade,
  unique (staff_id, date)
);

create index staff_restaurant_idx on public.staff (restaurant_id);
create index shifts_restaurant_date_idx on public.shifts (restaurant_id, date);
create index shifts_staff_date_idx on public.shifts (staff_id, date);

alter table public.staff enable row level security;
alter table public.shifts enable row level security;

grant select, insert, update on public.staff to anon;
grant select, insert, update on public.shifts to anon;

create policy "Prototype anon read staff"
on public.staff for select to anon
using (true);

create policy "Prototype anon create staff"
on public.staff for insert to anon
with check (true);

create policy "Prototype anon update staff"
on public.staff for update to anon
using (true) with check (true);

create policy "Prototype anon read shifts"
on public.shifts for select to anon
using (true);

create policy "Prototype anon create shifts"
on public.shifts for insert to anon
with check (true);

create policy "Prototype anon update shifts"
on public.shifts for update to anon
using (true) with check (true);

